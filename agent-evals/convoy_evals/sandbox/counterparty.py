"""CounterpartyEngine — scripted state machines playing the world's other
humans (carriers, insureds, portals). Deterministic by construction: all
semantics are script-chosen; the only randomness is a seeded mulberry32 PRNG
(bit-identical to the TS one, so scenario seeds behave the same) resolving
uniform delay distributions.

Port of src/sandbox/counterparty.ts. Presets expand to plain
CounterpartyRule[] at engine creation, so 'custom' and every profile share one
matching/firing engine. Deliveries go through a sim-time queue the DES driver
drains: peek() feeds the next-event computation, deliver_due() applies
everything due at the new now.
"""

from __future__ import annotations

import re
from datetime import datetime, timedelta
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Union

from pydantic import BaseModel, ConfigDict

from ..runtime.ports import ClockPort
from ..schema.scenario import (
    CounterpartyMatch,
    CounterpartyRespond,
    CounterpartyRule,
    CounterpartyScript,
    MessageTemplate,
    SimDelay,
    UniformDelay,
    parse_duration_ms,
)
from .api import WorldMessage, WorldRecord, WorldStore
from .emulators.util import AGENT_ADDRESS, thread_id_for_subject

# --- seeded PRNG -----------------------------------------------------------

_M32 = 0xFFFFFFFF


def mulberry32(a: int) -> Callable[[], float]:
    """Bit-exact port of the TS mulberry32: same seed → same stream."""
    state = a & _M32

    def rand() -> float:
        nonlocal state
        state = (state + 0x6D2B79F5) & _M32
        t = state
        t = ((t ^ (t >> 15)) * (1 | t)) & _M32
        t = ((t + (((t ^ (t >> 7)) * (61 | t)) & _M32)) ^ t) & _M32
        return ((t ^ (t >> 14)) & _M32) / 4294967296

    return rand


def _resolve_delay_ms(delay: Any, rand: Callable[[], float]) -> float:
    if isinstance(delay, str):
        return parse_duration_ms(delay)
    if isinstance(delay, UniformDelay):
        lo, hi = parse_duration_ms(delay.min), parse_duration_ms(delay.max)
    else:  # plain dict {dist:'uniform', min, max}
        lo, hi = parse_duration_ms(delay["min"]), parse_duration_ms(delay["max"])
    return lo + rand() * (hi - lo)


# --- preset expansion ------------------------------------------------------


class _PresetParams(BaseModel):
    """Mirror of the TS zod PresetParams (unknown keys stripped, like zod)."""

    model_config = ConfigDict(extra="ignore")
    replyTemplate: Optional[MessageTemplate] = None
    attachments: Optional[List[str]] = None
    wrongAttachment: Optional[str] = None
    injectionAttachment: Optional[str] = None
    # Portal fulfillment document (pack path) + delay.
    document: Optional[str] = None
    fulfillAfter: Optional[Union[str, UniformDelay]] = None
    # --- corpus conventions (scenarios generated by src/corpus/generate.ts) ---
    # Insured presets: reply body = this pack file's content (the exposure answer).
    exposureReplyFile: Optional[str] = None
    policyId: Optional[str] = None
    # Carrier presets: carrier display name (matches portal_request.fields.carrier).
    carrier: Optional[str] = None
    # Carrier presets: per-policy correct loss-run doc (pack path).
    lossRunsByPolicy: Optional[Dict[str, str]] = None
    # wrong-document carriers: per-policy wrong doc served on the FIRST request.
    wrongDocByPolicy: Optional[Dict[str, str]] = None


def carrier_slug(name: str) -> str:
    """'Blue Heron Casualty' → 'blueheroncasualty' (owns entries are 'portal:<slug>')."""
    return re.sub(r"[^a-z0-9]", "", name.lower())


# Sentinel subject: deliver as a reply to the triggering message's subject.
REPLY_SUBJECT = "@reply"

COOPERATIVE_DELAY = UniformDelay(dist="uniform", min="1d", max="2d")
PROMPT_DELAY: SimDelay = "1d"
MANY = 999


def _require_template(
    script: CounterpartyScript, params: _PresetParams, pack_dir: Optional[str]
) -> MessageTemplate:
    if params.replyTemplate is not None:
        return params.replyTemplate
    # Corpus convention: insured reply body comes from a pack file.
    if params.exposureReplyFile is not None and pack_dir is not None:
        body = (Path(pack_dir) / params.exposureReplyFile).read_text(encoding="utf-8")
        return MessageTemplate(subject=REPLY_SUBJECT, body=body)
    raise ValueError(
        "counterparty %s (profile %s): params.replyTemplate or params.exposureReplyFile required"
        % (script.actorId, script.profile)
    )


def expand_profile(
    script: CounterpartyScript, pack_dir: Optional[str] = None
) -> List[CounterpartyRule]:
    """Expand a profile preset into plain rules; 'custom' passes rules verbatim."""
    params = _PresetParams.model_validate(script.params or {})
    # Portal actors react to portal_request records, not to email — presets
    # expand to no message rules (custom rules still pass through below).
    if script.channel == "portal" and script.profile != "custom":
        return []

    def per_owned(make: Callable[[str, int], List[CounterpartyRule]]) -> List[CounterpartyRule]:
        out: List[CounterpartyRule] = []
        for i, addr in enumerate(script.owns):
            out.extend(make(addr, i))
        return out

    if script.profile == "cooperative":
        template = _require_template(script, params, pack_dir)
        return per_owned(
            lambda addr, i: [
                CounterpartyRule(
                    id="%s-coop-%d" % (script.actorId, i),
                    match=CounterpartyMatch(toContains=addr),
                    maxFires=MANY,
                    respond=[
                        CounterpartyRespond(
                            afterSim=COOPERATIVE_DELAY,
                            message=template,
                            attachments=params.attachments,
                        )
                    ],
                )
            ]
        )
    if script.profile == "slow":
        template = _require_template(script, params, pack_dir)
        # Reply only to the chase: occurrence 2 = the 2nd matching outbound message.
        return per_owned(
            lambda addr, i: [
                CounterpartyRule(
                    id="%s-slow-%d" % (script.actorId, i),
                    match=CounterpartyMatch(toContains=addr, occurrence=2),
                    maxFires=1,
                    respond=[
                        CounterpartyRespond(
                            afterSim=COOPERATIVE_DELAY,
                            message=template,
                            attachments=params.attachments,
                        )
                    ],
                )
            ]
        )
    if script.profile == "wrong-document":
        template = _require_template(script, params, pack_dir)
        if not params.wrongAttachment:
            raise ValueError(
                "counterparty %s: wrong-document profile requires params.wrongAttachment"
                % script.actorId
            )
        wrong = params.wrongAttachment
        return per_owned(
            lambda addr, i: [
                CounterpartyRule(
                    id="%s-wrongdoc-first-%d" % (script.actorId, i),
                    match=CounterpartyMatch(toContains=addr, occurrence=1),
                    maxFires=1,
                    respond=[
                        CounterpartyRespond(
                            afterSim=PROMPT_DELAY, message=template, attachments=[wrong]
                        )
                    ],
                ),
                CounterpartyRule(
                    id="%s-wrongdoc-correct-%d" % (script.actorId, i),
                    match=CounterpartyMatch(toContains=addr, occurrence=2),
                    maxFires=1,
                    respond=[
                        CounterpartyRespond(
                            afterSim=PROMPT_DELAY,
                            message=template,
                            attachments=params.attachments,
                        )
                    ],
                ),
            ]
        )
    if script.profile == "silent":
        return []
    if script.profile == "adversarial-injection":
        template = _require_template(script, params, pack_dir)
        if not params.injectionAttachment:
            raise ValueError(
                "counterparty %s: adversarial-injection profile requires params.injectionAttachment"
                % script.actorId
            )
        inject = params.injectionAttachment
        return per_owned(
            lambda addr, i: [
                CounterpartyRule(
                    id="%s-inject-%d" % (script.actorId, i),
                    match=CounterpartyMatch(toContains=addr),
                    maxFires=MANY,
                    respond=[
                        CounterpartyRespond(
                            afterSim=PROMPT_DELAY, message=template, attachments=[inject]
                        )
                    ],
                )
            ]
        )
    if script.profile == "custom":
        # NOTE: [] is allowed (matches TS, where `!script.rules` only catches
        # undefined) — an actor may exist only for its unsolicited sends.
        if script.rules is None:
            raise ValueError("counterparty %s: custom profile requires rules" % script.actorId)
        return list(script.rules)
    raise ValueError("unknown counterparty profile: %s" % script.profile)


# --- engine ----------------------------------------------------------------


class _RuleState:
    __slots__ = ("rule", "occurrence_count", "fires")

    def __init__(self, rule: CounterpartyRule) -> None:
        self.rule = rule
        self.occurrence_count = 0
        self.fires = 0


class _Actor:
    __slots__ = ("script", "rules")

    def __init__(self, script: CounterpartyScript, rules: List[_RuleState]) -> None:
        self.script = script
        self.rules = rules


class _QueueEntry:
    __slots__ = ("at", "seq", "fire")

    def __init__(self, at: datetime, seq: int, fire: Callable[[], None]) -> None:
        self.at = at
        self.seq = seq
        self.fire = fire


class CounterpartyEngine:
    """peek(): earliest queued sim-time delivery, or None when the queue is
    empty. deliver_due(now): apply every queued delivery due at `now`."""

    def __init__(
        self,
        scripts: List[Any],
        world: WorldStore,
        clock: ClockPort,
        seed: int,
        pack_dir: str,
    ) -> None:
        self._world = world
        self._clock = clock
        self._pack_dir = pack_dir
        self._rand = mulberry32(seed)
        t0 = clock.now()

        parsed: List[CounterpartyScript] = [
            s if isinstance(s, CounterpartyScript) else CounterpartyScript.model_validate(s)
            for s in scripts
        ]
        self._actors: List[_Actor] = [
            _Actor(script, [_RuleState(rule) for rule in expand_profile(script, pack_dir)])
            for script in parsed
        ]

        self._queue: List[_QueueEntry] = []
        self._queue_seq = 0
        self._fulfilled_portal_requests: set = set()
        # pack path → world file id (resolved lazily; falls back to reading pack_dir).
        self._pack_file_cache: Dict[str, str] = {}
        # Per-(actor, policy) fulfillment count — wrong-document serves the
        # wrong doc first, correct on re-request.
        self._portal_fulfill_counts: Dict[str, int] = {}

        def on_world_event(e: Dict[str, Any]) -> None:
            if e.get("kind") == "message_sent":
                self._on_outbound_message(e["message"])
            if (
                e.get("kind") == "record_changed"
                and e["record"].collection == "portal_request"
                and e["record"].fields.get("status") == "pending"
            ):
                self._on_portal_request_pending(e["record"])

        world.on_event(on_world_event)

        # Unsolicited sends: scheduled at t0 + atSim, delivered to the agent.
        for script in parsed:
            for u in script.unsolicited or []:
                at = t0 + timedelta(milliseconds=parse_duration_ms(u.atSim))
                attachments = [self._resolve_attachment(p) for p in (u.attachments or [])]
                self._schedule(at, self._make_unsolicited_fire(script, u.message, attachments))

    # -- queue -------------------------------------------------------------

    def _schedule(self, at: datetime, fire: Callable[[], None]) -> None:
        self._queue.append(_QueueEntry(at, self._queue_seq, fire))
        self._queue_seq += 1
        self._queue.sort(key=lambda q: (q.at, q.seq))

    def peek(self) -> Optional[datetime]:
        return self._queue[0].at if self._queue else None

    def deliver_due(self, now: datetime) -> None:
        while self._queue and self._queue[0].at <= now:
            entry = self._queue.pop(0)
            entry.fire()

    # -- attachments -------------------------------------------------------

    def _resolve_attachment(self, pack_path: str) -> Dict[str, str]:
        cached = self._pack_file_cache.get(pack_path)
        if cached:
            f = self._world.get_file(cached)
            if f:
                return {"name": f.name, "fileId": f.id}
        seeded = self._world.file_by_pack_path(pack_path)
        if seeded:
            self._pack_file_cache[pack_path] = seeded.id
            return {"name": seeded.name, "fileId": seeded.id}
        # Trap docs may live in the pack dir without being seeded into the world.
        content = (Path(self._pack_dir) / pack_path).read_text(encoding="utf-8")
        name = pack_path.split("/")[-1] or pack_path
        file = self._world.put_file(name=name, mime="text/plain", content=content)
        self._pack_file_cache[pack_path] = file.id
        return {"name": file.name, "fileId": file.id}

    # -- email rules -------------------------------------------------------

    def _make_unsolicited_fire(
        self, script: CounterpartyScript, message: MessageTemplate, attachments: List[Dict[str, str]]
    ) -> Callable[[], None]:
        def fire() -> None:
            self._world.deliver_message(
                threadId=thread_id_for_subject(message.subject),
                from_=message.from_ or (script.owns[0] if script.owns else script.actorId),
                to=[AGENT_ADDRESS],
                subject=message.subject,
                body=message.body,
                attachments=attachments,
                direction="inbound",
            )

        return fire

    def _schedule_replies(
        self,
        script: CounterpartyScript,
        rule: CounterpartyRule,
        trigger_from: str,
        trigger_thread_id: str,
        trigger_subject: str,
    ) -> None:
        for respond in rule.respond:
            delay_ms = _resolve_delay_ms(respond.afterSim, self._rand)
            at = self._clock.now() + timedelta(milliseconds=delay_ms)
            message = respond.message
            subject = (
                "Re: %s" % trigger_subject if message.subject == REPLY_SUBJECT else message.subject
            )
            attachments = [self._resolve_attachment(p) for p in (respond.attachments or [])]

            def fire(
                _subject: str = subject,
                _attachments: List[Dict[str, str]] = attachments,
                _message: MessageTemplate = message,
            ) -> None:
                self._world.deliver_message(
                    threadId=trigger_thread_id,
                    from_=_message.from_ or (script.owns[0] if script.owns else script.actorId),
                    to=[trigger_from],
                    subject=_subject,
                    body=_message.body,
                    attachments=_attachments,
                    direction="inbound",
                )

            self._schedule(at, fire)

    def _on_outbound_message(self, m: WorldMessage) -> None:
        for actor in self._actors:
            script = actor.script
            if script.channel != "email":
                continue
            # The actor only receives mail addressed to something it owns.
            if not any(any(o in addr for o in script.owns) for addr in m.to):
                continue

            for state in actor.rules:
                rule = state.rule
                match = rule.match
                if match.toContains and not any(match.toContains in addr for addr in m.to):
                    continue
                if match.subjectRegex and not re.search(match.subjectRegex, m.subject):
                    continue
                if match.bodyRegex and not re.search(match.bodyRegex, m.body):
                    continue
                if match.hasAttachment is not None and (len(m.attachments) > 0) != match.hasAttachment:
                    continue

                state.occurrence_count += 1  # nth matching outbound message, counted per rule
                if match.occurrence is not None and state.occurrence_count != match.occurrence:
                    continue
                if state.fires >= rule.maxFires:
                    continue

                state.fires += 1
                self._schedule_replies(script, rule, m.from_, m.threadId, m.subject)

    # -- portal fulfillment ------------------------------------------------

    def _on_portal_request_pending(self, record: WorldRecord) -> None:
        if record.id in self._fulfilled_portal_requests:
            return
        carrier = record.fields.get("carrier")
        if not isinstance(carrier, str):
            return

        actor: Optional[_Actor] = None
        for a in self._actors:
            if a.script.channel != "portal":
                continue
            p = _PresetParams.model_validate(a.script.params or {})
            if (
                carrier in a.script.owns
                or ("portal:%s" % carrier_slug(carrier)) in a.script.owns
                or p.carrier == carrier
            ):
                actor = a
                break
        if actor is None or actor.script.profile == "silent":
            return

        params = _PresetParams.model_validate(actor.script.params or {})
        policy_id = (
            record.fields["policyId"]
            if isinstance(record.fields.get("policyId"), str)
            else None
        )

        count_key = "%s:%s" % (actor.script.actorId, policy_id if policy_id else record.id)
        nth = self._portal_fulfill_counts.get(count_key, 0) + 1
        self._portal_fulfill_counts[count_key] = nth

        correct_doc = None
        if policy_id and params.lossRunsByPolicy:
            correct_doc = params.lossRunsByPolicy.get(policy_id)
        if correct_doc is None:
            correct_doc = params.document
        if correct_doc is None and params.attachments:
            correct_doc = params.attachments[0]

        document_path = correct_doc
        if actor.script.profile == "wrong-document" and nth == 1:
            wrong = None
            if policy_id and params.wrongDocByPolicy:
                wrong = params.wrongDocByPolicy.get(policy_id)
            document_path = wrong or params.wrongAttachment or correct_doc
        if not document_path:
            raise ValueError(
                "counterparty %s: portal fulfillment requires a document (lossRunsByPolicy/document)"
                % actor.script.actorId
            )

        self._fulfilled_portal_requests.add(record.id)
        delay: Any = params.fulfillAfter
        if delay is None:
            delay = COOPERATIVE_DELAY if actor.script.profile == "cooperative" else PROMPT_DELAY
        at = self._clock.now() + timedelta(milliseconds=_resolve_delay_ms(delay, self._rand))
        request_id = record.id
        resolved_path = document_path
        inject_path = (
            params.injectionAttachment
            if actor.script.profile == "adversarial-injection"
            else None
        )

        def fire() -> None:
            if inject_path:
                # Injection carriers deliver ONE download whose content is the
                # correct doc plus the poisoned addendum — the correct data is
                # present (golden must still pass) and the INSTRUCTION line is
                # present (violators obey).
                correct = (Path(self._pack_dir) / resolved_path).read_text(encoding="utf-8")
                addendum = (Path(self._pack_dir) / inject_path).read_text(encoding="utf-8")
                merged = self._world.put_file(
                    name="loss-run-with-addendum-%s.txt" % request_id,
                    mime="text/plain",
                    content="%s\n\n%s" % (correct, addendum),
                )
                doc = {"name": merged.name, "fileId": merged.id}
            else:
                doc = self._resolve_attachment(resolved_path)
            self._world.upsert_record(
                "portal_request",
                request_id,
                {"status": "fulfilled", "documentFileId": doc["fileId"]},
            )
            self._world.emit_event(
                {"kind": "portal_transition", "requestId": request_id, "to": "fulfilled"}
            )

        self._schedule(at, fire)


def create_counterparty_engine(
    scripts: List[Any],
    world: WorldStore,
    clock: ClockPort,
    seed: int,
    pack_dir: str,
) -> CounterpartyEngine:
    return CounterpartyEngine(scripts, world, clock, seed, pack_dir)
