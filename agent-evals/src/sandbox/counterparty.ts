/**
 * CounterpartyEngine — scripted state machines playing the world's other
 * humans (carriers, insureds, portals). Deterministic by construction: all
 * semantics are script-chosen; the only randomness is a seeded mulberry32
 * PRNG resolving uniform delay distributions.
 *
 * Presets expand to plain CounterpartyRule[] at engine creation, so 'custom'
 * and every profile share one matching/firing engine. Deliveries go through a
 * sim-time queue the DES driver drains: peek() feeds the next-event
 * computation, deliverDue() applies everything due at the new now.
 */

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { z } from 'zod';
import type { ClockPort } from '../runtime/ports.ts';
import {
  CounterpartyScriptSchema,
  MessageTemplateSchema,
  parseDuration,
  type CounterpartyRule,
  type CounterpartyScript,
  type SimDelay,
} from '../schema/scenario.ts';
import type { WorldStore } from './api.ts';
import { AGENT_ADDRESS, threadIdForSubject } from './emulators/util.ts';
import type { SimWorldStore } from './world.ts';

export interface CounterpartyEngine {
  /** Earliest queued sim-time delivery, or null when the queue is empty. */
  peek(): Date | null;
  /** Apply every queued delivery due at `now` (world.deliverMessage / upsertRecord). */
  deliverDue(now: Date): void;
}

export interface CounterpartyEngineOptions {
  scripts: CounterpartyScript[];
  world: WorldStore;
  clock: ClockPort;
  seed: number;
  packDir: string;
}

// --- seeded PRNG -----------------------------------------------------------

export function mulberry32(a: number): () => number {
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function resolveDelayMs(delay: SimDelay, rand: () => number): number {
  if (typeof delay === 'string') return parseDuration(delay);
  const min = parseDuration(delay.min);
  const max = parseDuration(delay.max);
  return min + rand() * (max - min);
}

// --- preset expansion ------------------------------------------------------

const PresetParams = z.object({
  replyTemplate: MessageTemplateSchema.optional(),
  attachments: z.array(z.string()).optional(),
  wrongAttachment: z.string().optional(),
  injectionAttachment: z.string().optional(),
  /** Portal fulfillment document (pack path) + delay. */
  document: z.string().optional(),
  fulfillAfter: z.union([z.string(), z.object({ dist: z.literal('uniform'), min: z.string(), max: z.string() })]).optional(),
  // --- corpus conventions (scenarios generated by src/corpus/generate.ts) ---
  /** Insured presets: reply body = this pack file's content (the exposure answer). */
  exposureReplyFile: z.string().optional(),
  policyId: z.string().optional(),
  /** Carrier presets: carrier display name (matches portal_request.fields.carrier). */
  carrier: z.string().optional(),
  /** Carrier presets: per-policy correct loss-run doc (pack path). */
  lossRunsByPolicy: z.record(z.string(), z.string()).optional(),
  /** wrong-document carriers: per-policy wrong doc served on the FIRST request. */
  wrongDocByPolicy: z.record(z.string(), z.string()).optional(),
});

/** 'Blue Heron Casualty' → 'blueheroncasualty' (owns entries are 'portal:<slug>'). */
function carrierSlug(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]/g, '');
}

/** Sentinel subject: deliver as a reply to the triggering message's subject. */
const REPLY_SUBJECT = '@reply';

const COOPERATIVE_DELAY: SimDelay = { dist: 'uniform', min: '1d', max: '2d' };
const PROMPT_DELAY: SimDelay = '1d';
const MANY = 999;

function requireTemplate(
  script: CounterpartyScript,
  params: z.infer<typeof PresetParams>,
  packDir?: string
) {
  if (params.replyTemplate) return params.replyTemplate;
  // Corpus convention: insured reply body comes from a pack file.
  if (params.exposureReplyFile && packDir) {
    const body = readFileSync(join(packDir, params.exposureReplyFile), 'utf8');
    return { subject: REPLY_SUBJECT, body };
  }
  throw new Error(
    `counterparty ${script.actorId} (profile ${script.profile}): params.replyTemplate or params.exposureReplyFile required`
  );
}

/** Expand a profile preset into plain rules; 'custom' passes rules verbatim. */
export function expandProfile(script: CounterpartyScript, packDir?: string): CounterpartyRule[] {
  const params = PresetParams.parse(script.params ?? {});
  // Portal actors react to portal_request records, not to email — presets
  // expand to no message rules (custom rules still pass through below).
  if (script.channel === 'portal' && script.profile !== 'custom') return [];
  const perOwned = (make: (addr: string, i: number) => CounterpartyRule[]): CounterpartyRule[] =>
    script.owns.flatMap((addr, i) => make(addr, i));

  switch (script.profile) {
    case 'cooperative': {
      const template = requireTemplate(script, params, packDir);
      return perOwned((addr, i) => [
        {
          id: `${script.actorId}-coop-${i}`,
          match: { toContains: addr },
          maxFires: MANY,
          respond: [{ afterSim: COOPERATIVE_DELAY, message: template, attachments: params.attachments }],
        },
      ]);
    }
    case 'slow': {
      const template = requireTemplate(script, params, packDir);
      // Reply only to the chase: occurrence 2 = the 2nd matching outbound message.
      return perOwned((addr, i) => [
        {
          id: `${script.actorId}-slow-${i}`,
          match: { toContains: addr, occurrence: 2 },
          maxFires: 1,
          respond: [{ afterSim: COOPERATIVE_DELAY, message: template, attachments: params.attachments }],
        },
      ]);
    }
    case 'wrong-document': {
      const template = requireTemplate(script, params, packDir);
      if (!params.wrongAttachment) {
        throw new Error(`counterparty ${script.actorId}: wrong-document profile requires params.wrongAttachment`);
      }
      return perOwned((addr, i) => [
        {
          id: `${script.actorId}-wrongdoc-first-${i}`,
          match: { toContains: addr, occurrence: 1 },
          maxFires: 1,
          respond: [{ afterSim: PROMPT_DELAY, message: template, attachments: [params.wrongAttachment!] }],
        },
        {
          id: `${script.actorId}-wrongdoc-correct-${i}`,
          match: { toContains: addr, occurrence: 2 },
          maxFires: 1,
          respond: [{ afterSim: PROMPT_DELAY, message: template, attachments: params.attachments }],
        },
      ]);
    }
    case 'silent':
      return [];
    case 'adversarial-injection': {
      const template = requireTemplate(script, params, packDir);
      if (!params.injectionAttachment) {
        throw new Error(`counterparty ${script.actorId}: adversarial-injection profile requires params.injectionAttachment`);
      }
      return perOwned((addr, i) => [
        {
          id: `${script.actorId}-inject-${i}`,
          match: { toContains: addr },
          maxFires: MANY,
          respond: [{ afterSim: PROMPT_DELAY, message: template, attachments: [params.injectionAttachment!] }],
        },
      ]);
    }
    case 'custom': {
      if (!script.rules) throw new Error(`counterparty ${script.actorId}: custom profile requires rules`);
      return script.rules;
    }
  }
}

// --- engine ----------------------------------------------------------------

interface QueueEntry {
  at: Date;
  seq: number;
  fire: () => void;
}

export function createCounterpartyEngine(opts: CounterpartyEngineOptions): CounterpartyEngine {
  const { world, clock, packDir } = opts;
  const simWorld = world as SimWorldStore;
  const rand = mulberry32(opts.seed);
  const t0 = clock.now();

  const scripts = opts.scripts.map((s) => CounterpartyScriptSchema.parse(s));
  const actors = scripts.map((script) => ({
    script,
    rules: expandProfile(script, packDir).map((rule) => ({ rule, occurrenceCount: 0, fires: 0 })),
  }));

  const queue: QueueEntry[] = [];
  let queueSeq = 0;
  const fulfilledPortalRequests = new Set<string>();
  /** pack path → world file id (resolved lazily; falls back to reading packDir). */
  const packFileCache = new Map<string, string>();

  function schedule(at: Date, fire: () => void): void {
    queue.push({ at, seq: queueSeq++, fire });
    queue.sort((a, b) => a.at.getTime() - b.at.getTime() || a.seq - b.seq);
  }

  function resolveAttachment(packPath: string): { name: string; fileId: string } {
    const cached = packFileCache.get(packPath);
    if (cached) {
      const f = world.getFile(cached);
      if (f) return { name: f.name, fileId: f.id };
    }
    const seeded = world.fileByPackPath(packPath);
    if (seeded) {
      packFileCache.set(packPath, seeded.id);
      return { name: seeded.name, fileId: seeded.id };
    }
    // Trap docs may live in the pack dir without being seeded into the world.
    const content = readFileSync(join(packDir, packPath), 'utf8');
    const name = packPath.split('/').pop() ?? packPath;
    const file = world.putFile({ name, mime: 'text/plain', content });
    packFileCache.set(packPath, file.id);
    return { name: file.name, fileId: file.id };
  }

  function scheduleReplies(
    script: CounterpartyScript,
    rule: CounterpartyRule,
    trigger: { from: string; threadId: string; subject: string }
  ): void {
    for (const respond of rule.respond) {
      const delayMs = resolveDelayMs(respond.afterSim, rand);
      const at = new Date(clock.now().getTime() + delayMs);
      const message = respond.message;
      const subject = message.subject === REPLY_SUBJECT ? `Re: ${trigger.subject}` : message.subject;
      const attachments = (respond.attachments ?? []).map(resolveAttachment);
      schedule(at, () => {
        world.deliverMessage({
          threadId: trigger.threadId,
          from: message.from ?? script.owns[0] ?? script.actorId,
          to: [trigger.from],
          subject,
          body: message.body,
          attachments,
          direction: 'inbound',
        });
      });
    }
  }

  function onOutboundMessage(m: { from: string; to: string[]; subject: string; body: string; threadId: string; attachments: Array<{ name: string; fileId: string }> }): void {
    for (const actor of actors) {
      const { script } = actor;
      if (script.channel !== 'email') continue;
      // The actor only receives mail addressed to something it owns.
      if (!m.to.some((addr) => script.owns.some((o) => addr.includes(o)))) continue;

      for (const state of actor.rules) {
        const { rule } = state;
        const match = rule.match;
        if (match.toContains && !m.to.some((addr) => addr.includes(match.toContains!))) continue;
        if (match.subjectRegex && !new RegExp(match.subjectRegex).test(m.subject)) continue;
        if (match.bodyRegex && !new RegExp(match.bodyRegex).test(m.body)) continue;
        if (match.hasAttachment !== undefined && m.attachments.length > 0 !== match.hasAttachment) continue;

        state.occurrenceCount += 1; // nth matching outbound message, counted per rule
        if (match.occurrence !== undefined && state.occurrenceCount !== match.occurrence) continue;
        if (state.fires >= rule.maxFires) continue;

        state.fires += 1;
        scheduleReplies(script, rule, { from: m.from, threadId: m.threadId, subject: m.subject });
      }
    }
  }

  /** Per-(actor, policy) fulfillment count — wrong-document serves the wrong doc first, correct on re-request. */
  const portalFulfillCounts = new Map<string, number>();

  function onPortalRequestPending(record: { id: string; fields: Record<string, unknown> }): void {
    if (fulfilledPortalRequests.has(record.id)) return;
    const carrier = record.fields['carrier'];
    if (typeof carrier !== 'string') return;
    const actor = actors.find((a) => {
      if (a.script.channel !== 'portal') return false;
      const p = PresetParams.parse(a.script.params ?? {});
      return (
        a.script.owns.includes(carrier) ||
        a.script.owns.includes(`portal:${carrierSlug(carrier)}`) ||
        p.carrier === carrier
      );
    });
    if (!actor || actor.script.profile === 'silent') return;
    const params = PresetParams.parse(actor.script.params ?? {});
    const policyId = typeof record.fields['policyId'] === 'string' ? (record.fields['policyId'] as string) : undefined;

    const countKey = `${actor.script.actorId}:${policyId ?? record.id}`;
    const nth = (portalFulfillCounts.get(countKey) ?? 0) + 1;
    portalFulfillCounts.set(countKey, nth);

    const correctDoc =
      (policyId && params.lossRunsByPolicy?.[policyId]) ?? params.document ?? params.attachments?.[0];
    let documentPath = correctDoc;
    if (actor.script.profile === 'wrong-document' && nth === 1) {
      documentPath = (policyId && params.wrongDocByPolicy?.[policyId]) ?? params.wrongAttachment ?? correctDoc;
    }
    if (!documentPath) {
      throw new Error(`counterparty ${actor.script.actorId}: portal fulfillment requires a document (lossRunsByPolicy/document)`);
    }
    fulfilledPortalRequests.add(record.id);
    const delay: SimDelay = (params.fulfillAfter as SimDelay | undefined) ??
      (actor.script.profile === 'cooperative' ? COOPERATIVE_DELAY : PROMPT_DELAY);
    const at = new Date(clock.now().getTime() + resolveDelayMs(delay, rand));
    const requestId = record.id;
    const resolvedPath = documentPath;
    const injectPath = actor.script.profile === 'adversarial-injection' ? params.injectionAttachment : undefined;
    schedule(at, () => {
      let doc: { name: string; fileId: string };
      if (injectPath) {
        // Injection carriers deliver ONE download whose content is the correct
        // doc plus the poisoned addendum — the correct data is present (golden
        // must still pass) and the INSTRUCTION line is present (violators obey).
        const correct = readFileSync(join(packDir, resolvedPath), 'utf8');
        const addendum = readFileSync(join(packDir, injectPath), 'utf8');
        const merged = world.putFile({
          name: `loss-run-with-addendum-${requestId}.txt`,
          mime: 'text/plain',
          content: `${correct}\n\n${addendum}`,
        });
        doc = { name: merged.name, fileId: merged.id };
      } else {
        doc = resolveAttachment(resolvedPath);
      }
      world.upsertRecord('portal_request', requestId, { status: 'fulfilled', documentFileId: doc.fileId });
      if (typeof simWorld.emitEvent === 'function') {
        simWorld.emitEvent({ kind: 'portal_transition', requestId, to: 'fulfilled' });
      }
    });
  }

  world.onEvent((e) => {
    if (e.kind === 'message_sent') onOutboundMessage(e.message);
    if (e.kind === 'record_changed' && e.record.collection === 'portal_request' && e.record.fields['status'] === 'pending') {
      onPortalRequestPending(e.record);
    }
  });

  // Unsolicited sends: scheduled at t0 + atSim, delivered to the agent.
  for (const script of scripts) {
    for (const u of script.unsolicited ?? []) {
      const at = new Date(t0.getTime() + parseDuration(u.atSim));
      const attachments = (u.attachments ?? []).map(resolveAttachment);
      schedule(at, () => {
        world.deliverMessage({
          threadId: threadIdForSubject(u.message.subject),
          from: u.message.from ?? script.owns[0] ?? script.actorId,
          to: [AGENT_ADDRESS],
          subject: u.message.subject,
          body: u.message.body,
          attachments,
          direction: 'inbound',
        });
      });
    }
  }

  return {
    peek(): Date | null {
      return queue.length ? new Date(queue[0]!.at.getTime()) : null;
    },
    deliverDue(now: Date): void {
      while (queue.length && queue[0]!.at.getTime() <= now.getTime()) {
        const entry = queue.shift()!;
        entry.fire();
      }
    },
  };
}
